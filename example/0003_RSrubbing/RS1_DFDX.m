function [DFDX,DFDDX] = RS1_DFDX(x,dx,p,theta)
% Zeta  = 0.05;
% Beta  = 0.04;
R0    = 1.05;
R_d   = 20*R0;
%--------------------------------------------------------
issmooth = 1;
isfwithu = 1;
%--------------------------------------------------------
% m  = 1;
% cs = 2*Zeta;
% ks = Beta;
% e  = R0/1.05;
kc = 1;
r0 = R0;
rd = R_d;
%--------------------------------------------------------
X = x(1,:);
Y = x(2,:);
U = dx(1,:);
V = dx(2,:);
%--------------------------------------------------------
mu = p(1,:);
OM = p(2,:);
%--------------------------------------------------------
% theta1 = theta(1,:);
%--------------------------------------------------------
S = length(X);
DFDX = zeros(2,2,S);
DFDDX = []; 
%----------------------------------------------------------
r = (X.^2 + Y.^2).^0.5;
if issmooth == 1
    Theta = double(r - r0 >= 0);
else
    Theta = ones(1,S);
end
if isfwithu == 1
    vrel = rd.*OM + (X.*V - U.*Y)./r;
    Nu = sign(vrel);
else
    Nu = ones(1,S);
end
part1  = kc * Theta .* (1 - r0./r);
part2_1 = X - mu.*Nu.*Y;
part2_2 = mu.*Nu.*X + Y;
%----------------------------------------------------------
dpart1_dX = kc * Theta .* r0 .* X ./ r.^3;
dpart1_dY = kc * Theta .* r0 .* Y ./ r.^3;
dF1_dX = - dpart1_dX.*part2_1  -  part1;
dF1_dY = - dpart1_dY.*part2_1  +  part1 .* mu.*Nu;
dF2_dX = - dpart1_dX.*part2_2  -  part1 .* mu.*Nu;
dF2_dY = - dpart1_dY.*part2_2  -  part1;
%----------------------------------------------------------
DFDX(1,1,:) = dF1_dX;
DFDX(1,2,:) = dF1_dY;
DFDX(2,1,:) = dF2_dX;
DFDX(2,2,:) = dF2_dY;
%--------------------------------------------------------
end

