function DFDTH = RS1_DFDTH(x,dx,p,theta)
% Zeta  = 0.05;
% Beta  = 0.04;
R0    = 1.05;
% R_d   = 20*R0;
% %--------------------------------------------------------
% issmooth = 1;
% isfwithu = 1;
% %--------------------------------------------------------
m  = 1;
% % cs = 2*Zeta;
% % ks = Beta;
e  = R0/1.05;
% kc = 1;
% r0 = R0;
% rd = R_d;
% %--------------------------------------------------------
% X = x(1,:);
% Y = x(2,:);
% U = dx(1,:);
% V = dx(2,:);
%--------------------------------------------------------
% mu = p(1,:);
OM = p(2,:);
%--------------------------------------------------------
theta1 = theta(1,:);
%--------------------------------------------------------
DFDTH  = zeros(2,1,numel(theta1));
%--------------------------------------------------------
DFDTH(1,1,:) = - m*e*OM.^2.*sin(theta1);
DFDTH(2,1,:) =   m*e*OM.^2.*cos(theta1);
%--------------------------------------------------------
end


