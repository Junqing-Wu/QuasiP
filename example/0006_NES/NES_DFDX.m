function DFDX = NES_DFDX(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
x2 = x(2,:);
%----------------------------------------------------------
% theta1 = theta(1,:);
%----------------------------------------------------------
eps  = 0.1;
% BB   = p(1,:);
knl  = p(2,:);
% AA   = p(3,:);
%----------------------------------------------------------
DFDX = zeros(2,2,length(x1));
DFDX(1,1,:) = - 3*eps*knl.*(x1-x2).^2;
DFDX(1,2,:) =   3*eps*knl.*(x1-x2).^2;

DFDX(2,1,:) =   3*eps*knl.*(x2-x1).^2;
DFDX(2,2,:) = - 3*eps*knl.*(x2-x1).^2;
end
