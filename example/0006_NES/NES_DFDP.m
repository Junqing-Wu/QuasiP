function DFDP = NES_DFDP(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
x2 = x(2,:);
%----------------------------------------------------------
theta1 = theta(1,:);
%----------------------------------------------------------
eps  = 0.1;
% BB   = p(1,:);
% knl  = p(2,:);
% AA   = p(3,:);
%----------------------------------------------------------
DFDP = zeros(2,3,length(x1));
DFDP(1,2,:) = - eps*(x1-x2).^3;
DFDP(2,2,:) = - eps*(x2-x1).^3;
DFDP(1,3,:) =   eps*cos(theta1);
end