function DFDTH = NES_DFDTH(x,p,theta)
%----------------------------------------------------------
% x1 = x(1,:);
% x2 = x(2,:);
%----------------------------------------------------------
theta1 = theta(1,:);
%----------------------------------------------------------
eps  = 0.1;
% BB   = p(1,:);
% knl  = p(2,:);
AA   = p(3,:);
%----------------------------------------------------------
DFDTH = zeros(2,1,length(theta1));
DFDTH(1,:) = - eps*AA.*sin(theta1);
end