function F = NES_F(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
x2 = x(2,:);
%----------------------------------------------------------
theta1 = theta(1,:);
%----------------------------------------------------------
eps  = 0.1;
% BB   = p(1,:);
knl  = p(2,:);
AA   = p(3,:);
%----------------------------------------------------------
F = zeros(2,numel(x1));
F(1,:) = - eps*knl.*(x1-x2).^3 + eps*AA.*cos(theta1);
F(2,:) = - eps*knl.*(x2-x1).^3;
end