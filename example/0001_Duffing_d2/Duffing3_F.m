function F = Duffing3_F(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
% x2 = x(2,:);
%----------------------------------------------------------
theta1 = theta(1,:);
theta2 = theta(2,:);
%----------------------------------------------------------
% zeta = p(1,:);
gama = p(2,:);
f1   = p(3,:);
f2   = p(4,:);
%----------------------------------------------------------
F = zeros(2,length(x1));
F(1,:) = - gama.*x1.^3 + f1.*sin(theta1) + f2.*sin(theta2);
end