function F = PDuffing1_F(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
%----------------------------------------------------------
% zeta = p(1,:);
gama = p(2,:);
f1   = p(3,:);
%----------------------------------------------------------
F   = -gama.*x1.^3 + f1.*sin(theta1) + 5*sin(7*theta1);
end