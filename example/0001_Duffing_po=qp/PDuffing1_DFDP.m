function DFDP = PDuffing1_DFDP(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
%----------------------------------------------------------
% zeta = p(1,:);
% gama = p(2,:);
% f1   = p(3,:);
% f2   = p(4,:);
%----------------------------------------------------------
DFDP = zeros(1,4,length(x1));
DFDP(1,2,:) = -x1.^3;
DFDP(1,3,:) = sin(theta1);
end
