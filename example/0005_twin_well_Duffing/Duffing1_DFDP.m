function DFDP = Duffing1_DFDP(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
%----------------------------------------------------------
DFDP = zeros(1,3,length(x1));
DFDP(1,2,:) = -x1.^3;
DFDP(1,3,:) = cos(theta1);
end
