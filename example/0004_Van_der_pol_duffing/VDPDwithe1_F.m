function F = VDPDwithe1_F(x,dx,p,theta)
%----------------------------------------------------------
Mu      = 0.2;
Alpha   = 0.5;
e1      = 2;
%----------------------------------------------------------
q = x(1,:);
qdot = dx(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
%----------------------------------------------------------
F   = - (Mu*q.^2.*qdot + Alpha*q.^3) + e1*sin(theta1);
end