function F = Duffing_F4(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
theta2 = theta(2,:);
theta3 = theta(3,:);
theta4 = theta(4,:);
%----------------------------------------------------------
gama = 0.2;
%----------------------------------------------------------
F   = -gama.*x1.^3 + 5*sin(theta1) + 5*sin(theta2) + 5*sin(theta3) + 5*sin(theta4) ;
end