function [DFDX,DFDDX]= VDPD_DFDX(x,dx,p,theta)
%----------------------------------------------------------
Mu      = 0.2;
Alpha   = 0.5;
%----------------------------------------------------------
q = x(1,:);
qdot = dx(1,:);
%----------------------------------------------------------
df1_dq1 = 2*Mu*q.*qdot + 3*Alpha*q.^2;
df1_dqdot1 = Mu*q.^2;
%----------------------------------------------------------
DFDX = zeros(1,1,length(q));
DFDX(1,1,:)   = - df1_dq1;
DFDDX = zeros(1,1,length(q));
DFDDX(1,1,:)  = - df1_dqdot1;
end