function F = VDPDwithe3_F(x,dx,p,theta)
%----------------------------------------------------------
Mu      = 0.2;
Alpha   = 0.5;
e1      = 2;
e2      = 1;
e3      = 0.5;
%----------------------------------------------------------
q = x(1,:);
qdot = dx(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
theta2 = theta(2,:);
theta3 = theta(3,:);
%----------------------------------------------------------
F   = - (Mu*q.^2.*qdot + Alpha*q.^3) + e1*sin(theta1) + e2*sin(theta2) + e3*sin(theta3);
end
