function F = Duffing_F2(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
theta2 = theta(2,:);
%----------------------------------------------------------
gama = 0.2;
%----------------------------------------------------------
F   = -gama.*x1.^3 + 5*sin(theta1) + 5*sin(theta2);
end