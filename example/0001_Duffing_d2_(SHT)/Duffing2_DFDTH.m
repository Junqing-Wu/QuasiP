function DFDTH = Duffing2_DFDTH(x,p,theta)
%----------------------------------------------------------
theta1 = theta(1,:);
theta2 = theta(2,:);
%----------------------------------------------------------
% zeta = p(1,:);
% gama = p(2,:);
f1   = p(3,:);
f2   = p(4,:);
%----------------------------------------------------------
DFDTH = zeros(2,2,numel(theta1));
DFDTH(2,1,:) = f1.*cos(theta1);
DFDTH(2,2,:) = f2.*cos(theta2);
end