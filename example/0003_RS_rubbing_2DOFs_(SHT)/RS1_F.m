function F = RS1_F(x,dx,p,theta)
% Zeta  = 0.05;
% Beta  = 0.04;
R0    = 1.05;
R_d   = 20*R0;
%--------------------------------------------------------
issmooth = 1;
isfwithu = 1;
%--------------------------------------------------------
m  = 1;
% cs = 2*Zeta;
% ks = Beta;
e  = R0/1.05;
kc = 1;
r0 = R0;
rd = R_d;
%--------------------------------------------------------
X = x(1,:);
Y = x(2,:);
U = dx(1,:);
V = dx(2,:);
%--------------------------------------------------------
mu = p(1,:);
OM = p(2,:);
%--------------------------------------------------------
theta1 = theta(1,:);
%--------------------------------------------------------
S = length(X);
F = zeros(2,S);
%--------------------------------------------------------
r = (X.^2 + Y.^2).^(1/2);
if issmooth == 1
    Theta = double(r-r0>=0);
else
    Theta = ones(1,S);
end
if isfwithu == 1
    vrel = rd.*OM+(X.*V-U.*Y)./r;
    Nu = sign(vrel);
else
    Nu = ones(1,S);
end
part1  = kc * Theta .* (1 - r0./r);
part2_1 = X - mu.*Nu.*Y;
part2_2 = mu.*Nu.*X + Y;
%--------------------------------------------------------
F(1,:) = - part1.*part2_1 + m*e*OM.^2.*cos(theta1);
F(2,:) = - part1.*part2_2 + m*e*OM.^2.*sin(theta1);
%--------------------------------------------------------
end


