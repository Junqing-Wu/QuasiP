function F = Duffing1_F(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
%----------------------------------------------------------
b   = p(2,:);
f1  = p(3,:);
f2  = p(4,:);
%----------------------------------------------------------
theta1 = theta(1,:);
theta2 = theta(2,:);
%----------------------------------------------------------
F   = -b.*x1.^3 + f1.*cos(theta1) + f2.*cos(theta2);
end