function F = Duffing1_F(x,p,theta)
%----------------------------------------------------------
x1 = x(1,:);
%----------------------------------------------------------
theta1 = theta(1,:);
theta2 = theta(2,:);
%----------------------------------------------------------
% zeta = 0.1;
gama = 0.2;
f1   = 5;
f2   = 5;
%----------------------------------------------------------
F   = -gama.*x1.^3 + f1.*sin(theta1) + f2.*sin(theta2);
end